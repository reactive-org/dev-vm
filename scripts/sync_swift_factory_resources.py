#!/usr/bin/env python3
"""Offline release preparation only; no downloads, Docker, packages or guests.

The maintained Python staging oracle prepares the reviewed Linux recipe once.
The shipped Swift controller consumes these exact bytes without Mac Python/Git.
"""
import gzip
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "Sources/DevVMProvisioningCore/Resources/FactoryBuild"


def compress_template(data):
    compressed = io.BytesIO()
    with gzip.GzipFile(fileobj=compressed, mode="wb", filename="", mtime=0, compresslevel=9) as zipped:
        zipped.write(data)
    return compressed.getvalue()


def generate(check=False):
    spec = importlib.util.spec_from_file_location("factory_oracle", ROOT / "scripts/omarchy_image.py")
    oracle = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(oracle)
    lock = json.loads((ROOT / "omarchy/image/inputs.lock.json").read_bytes())
    with tempfile.TemporaryDirectory(prefix="factory-resource-") as directory:
        stage = Path(directory)
        oracle.stage_inputs(ROOT / "omarchy/image" / lock["guest_source"]["archive"], stage, lock)
        entries = {}
        stream = io.BytesIO()
        with tarfile.open(fileobj=stream, mode="w", format=tarfile.USTAR_FORMAT) as archive:
            for path in sorted(stage.rglob("*")):
                if path.is_symlink() or not (path.is_file() or path.is_dir()):
                    raise ValueError("Nonregular prepared input")
                name = path.relative_to(stage).as_posix()
                info = archive.gettarinfo(str(path), name)
                info.uid = info.gid = info.mtime = 0
                info.uname = info.gname = ""
                info.mode = 0o755 if path.is_dir() or path.stat().st_mode & 0o111 else 0o644
                if path.is_file():
                    data = path.read_bytes()
                    entries[name] = {"sha256": hashlib.sha256(data).hexdigest(), "mode": info.mode}
                    archive.addfile(info, io.BytesIO(data))
                else:
                    archive.addfile(info)
        if check:
            # Python/zlib releases can encode the same tar differently. Compare
            # the exact canonical tar against the oracle, without rewriting or
            # recompressing the committed payload. The recipe/pin checks below
            # still bind the exact compressed bytes shipped to Swift.
            payload = (OUT / "template.tar.gz").read_bytes()
            if gzip.decompress(payload) != stream.getvalue():
                raise ValueError("Prepared Swift factory archive contents differ from the maintained staging oracle")
        else:
            payload = compress_template(stream.getvalue())
        _, provenance = oracle.input_identity(lock["managed_try_commit"], 20)
        provenance["integration_package"] = {**lock["reviewed_integration"], "reused_reviewed_archive": True}
        downloads = [{"name": f"{repo}-{commit}.tar.gz", "url": f"https://codeload.github.com/omacom/{repo}/tar.gz/{commit}", "sha256": lock["archives"][repo]} for repo, commit in (("omarchy", lock["omarchy_commit"]), ("omarchy-pkgs", lock["recipes_commit"]))]
        version = lock["node_file"].split("-linux-", 1)[0][5:]
        downloads.append({"name": lock["node_file"], "url": f"https://nodejs.org/dist/{version}/{lock['node_file']}", "sha256": lock["node_sha256"]})
        manifest = {"format": 1, "templateSHA256": hashlib.sha256(payload).hexdigest(), "files": entries, "downloads": downloads, "provenance": provenance}
        data = (json.dumps(manifest, sort_keys=True, indent=2) + "\n").encode()
        pin = ('// Generated by scripts/sync_swift_factory_resources.py.\n'
               'enum FactoryRecipePin { static let sha256 = "' + hashlib.sha256(data).hexdigest() + '" }\n').encode()
        outputs = {OUT / "template.tar.gz": payload, OUT / "recipe.json": data,
                   ROOT / "Sources/DevVMProvisioningCore/FactoryRecipePin.swift": pin}
        for path, contents in outputs.items():
            if check:
                if not path.is_file() or path.read_bytes() != contents:
                    raise ValueError(f"Prepared Swift factory resource {path.name} differs from the maintained staging oracle")
            else:
                path.parent.mkdir(exist_ok=True)
                path.write_bytes(contents)
        print(f"Prepared {len(entries)} reviewed inputs; {len(payload)} archive bytes. No image build.")


if __name__ == "__main__":
    import sys
    generate(check="--check" in sys.argv[1:])
